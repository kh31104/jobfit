import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {industryJobPlan,suggestedSource} from '../../instructor/industry-public-pilot/plan.mjs';
import {transform,csvParse} from '../../supabase/functions/industry-public-pilot/lib.mjs';
const browserPlan=readFileSync(new URL('../../instructor/industry-public-pilot/plan.mjs',import.meta.url),'utf8');
const edgePlan=readFileSync(new URL('../../supabase/functions/industry-public-pilot/plan.mjs',import.meta.url),'utf8');
assert.equal(browserPlan,edgePlan,'UI and server must use exactly the same source recommendation rules');
const edu=industryJobPlan('교육산업','교육기획');
assert.equal(edu.sector,'education');
assert.equal(suggestedSource(edu,'bsi'),null,'Manufacturing BSI must never be recommended for education');
assert.equal(suggestedSource(edu,'support').keyword,'교육');
assert.equal(suggestedSource(edu,'ethics').keyword,'교육');
assert.match(edu.uncovered,/교육부/);
const eduUniversity=industryJobPlan('전국 대학','대학교수');
assert.equal(eduUniversity.sector,'education');
assert.equal(suggestedSource(eduUniversity,'bsi'),null);
const manuf=industryJobPlan('반도체 제조업','공정기술');
assert.equal(manuf.sector,'manufacturing');
assert.equal(suggestedSource(manuf,'bsi').keyword,'반도체');
const auto=industryJobPlan('자동차 제조업','품질관리');
assert.equal(suggestedSource(auto,'bsi').keyword,'자동차');
const tech=industryJobPlan('AI 소프트웨어','데이터 분석');
assert.equal(tech.sector,'technology');
assert.equal(suggestedSource(tech,'bsi'),null);
assert.equal(suggestedSource(tech,'ethics').keyword,'인공지능');
const finance=industryJobPlan('금융업','은행원');
assert.equal(suggestedSource(finance,'bsi'),null);
assert.equal(industryJobPlan('우주관광 산업','승무원').suggestions.length,0);
assert.equal(industryJobPlan('','교육기획').suggestions.length,0);
const mockSupport=csvParse('분야,공고명,소관기관,수행기관,신청시작일자,신청종료일자,등록일자,상세URL\n인력,청년 교육훈련 지원,정부,기관,2026-01-01,2026-02-01,2025-12-01,https://www.bizinfo.go.kr/example\n금융,금융지원,정부,기관,2026-01-01,2026-02-01,2025-12-01,https://www.bizinfo.go.kr/example2\n');
const relevant=transform('support',mockSupport,suggestedSource(edu,'support').keyword,10);
assert.equal(relevant.matched,1,'Guided education query must not return unrelated finance item');
assert.match(relevant.records[0].title,/교육훈련/);
const serverSource=readFileSync(new URL('../../supabase/functions/industry-public-pilot/index.ts',import.meta.url),'utf8');
assert(serverSource.includes("source_not_relevant"),'Server must reject unrelated source');
assert(serverSource.includes("mode==='guided'?selection.keyword"),'Server must enforce server-side keyword');
console.log('Industry and target-job relevance contract PASS: education, faculty, manufacturing, IT, finance, unknown, protected guided matching');
